// A glyph is five cells wide and seven high, and each one takes six cells across with the
// space after it.
export const ROWS = 7;
const ADVANCE = 6;

// The width of `text` set in cells `cell` wide, from its first cell to its last.
export function typeWidth(text, cell) {
  return (text.length * ADVANCE - 1) * cell;
}

// The top left corner of every filled cell of `text`, set with its top left corner at x, y.
export function typeCells(text, x, y, cell) {
  const cells = [];
  [...text].forEach((ch, k) => {
    const glyph = GLYPHS[ch];
    if (!glyph) throw new Error(`Stone type has no glyph for ${JSON.stringify(ch)}.`);
    glyph.forEach((row, r) => [...row].forEach((v, c) => {
      if (v === "#") cells.push([x + (k * ADVANCE + c) * cell, y + r * cell]);
    }));
  });
  return cells;
}

// The cells as one shape, each a square `size` cells across centred in its cell: the cell
// itself, or larger, so neighbours join into a ring round the letters.
export function typeShape(cells, cell, size = 1) {
  const p = new Path2D(), side = cell * size, inset = (cell - side) / 2;
  for (const [x, y] of cells) p.rect(x + inset, y + inset, side, side);
  return p;
}
